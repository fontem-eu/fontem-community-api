# ── Public data types ──────────────────────────────────────────


@dataclass(frozen=True)
# A turn genuinely carries this much: who is asking, in which conversation,
# what they said, what is on screen, where they are, whose key pays, and
# which model. Splitting it into sub-objects would only move the count.
# pylint: disable=too-many-instance-attributes
class ChatRequest:
    #: None for a signed-out visitor. Every persistence path in `turn` keys
    #: off this being set: an anonymous turn writes no conversation, no
    #: messages, no tool rows, no usage and no activity. That is the point
    #: rather than a simplification — `assist_conversations.user_id` is NOT
    #: NULL, and the alternative (mint a synthetic id per visitor) would let
    #: unauthenticated traffic write unbounded rows into the tables the usage
    #: reports read.
    user_id: str | None
    conversation_key: str
    message: str
    context_block: str
    #: Whether the caller has an editing surface to propose into. None for
    #: clients that predate the field; see `turn` for the fallback.
    has_editor: bool | None = None
    #: Current location + the site map, generated by the frontend from its
    #: own router and sent with the turn. See src/assistant/navigation.py
    #: for why it is not held server-side.
    nav: dict | None = None
    #: The caller's own provider credential, resolved before the turn.
    #: (provider, api_key, model) or None when they have not configured
    #: one — in which case the turn falls back to the platform key if one
    #: is still configured, and otherwise fails with a legible message.
    credential: tuple[str, str, str | None] | None = None
    #: Which built-in model to use when there is no credential. A curated
    #: id from src/assistant/local_models.py, resolved to a served name by
    #: the proxy client — never a filename from the caller.
    local_model_id: str | None = None


#: How long a signed-out visitor's message may be.
#:
#: The reduced assistant answers questions about the platform and moves the
#: caller around it. Those questions are short. A cap keeps the shape of the
#: turn honest — an unauthenticated caller cannot use the prompt as a way to
#: buy a large context on the shared llama-server, which the 20/hour limit
#: alone would not stop (one request can be as long as the body allows).
#:
#: `context_block` needs no equivalent: it is already truncated to the
#: service's own char budget before it reaches the model.
#:
#: fontem-web mirrors this number in AssistPanel.vue so the input stops the
#: user before the request does. Rejected rather than truncated: a silently
#: shortened question gets a confident answer to something nobody asked.
ANONYMOUS_MAX_PROMPT_CHARS = 1_000


@dataclass(frozen=True)
class UsageSnapshot:
    tokens_1h: int
    tokens_24h: int
    tokens_7d: int


